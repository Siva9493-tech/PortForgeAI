	async doHydrate() {
		try {
			const { data } = await getCurrentSession();
			const userId = data.session?.user?.id ?? null;
			if (userId) {
				this.currentUserId = userId;
				this.markLastUser(userId);
				try {
					const remote = await listForUser(userId);
					this.records = remote;
				} catch (error) {
					console.error("[portfolio-store] Failed to load portfolios from Supabase; using cached copy.", error);
					this.restore();
				}
			} else {
				this.clearLastUser();
				this.currentUserId = null;
				this.records = [];
				this.restore();
			}
		} finally {
			this.sessionResolved = true;
			this.notify();
		}
	}
